"""Write the CIE tables the spectral reader integrates against.

A reference file that carries **spectra and nothing else** has to be turned into
XYZ before anything can be compared with it, and that is an integration against
two published tables: a standard observer's colour-matching functions and an
illuminant's relative spectral power. Those are *data*, not algorithm, and this
project's rule is that data of this kind lives in the repository where it can be
read and checked against its publication rather than being fetched at runtime.

They are **generated rather than transcribed**, because eighty-one rows of four
columns typed by hand is a defect waiting to happen and the failure would be a
few hundredths of a Delta E -- invisible, and wrong. `colour-science` is the
source, which the project already declares as a dependency; the numbers it
publishes are the CIE's, and `tests/test_spectral.py` re-derives the D50 white
point from what is written here as an independent check on the result.

Run from the repository root when the table needs regenerating:

    python tools/generate_cie_tables.py
"""

from __future__ import annotations

from pathlib import Path

import colour
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "deltachrome" / "reference" / "cie_data.py"

#: The grid everything is written on. 5 nm from 360 to 830 covers every reference
#: file this project has seen -- the widest is 380 to 780 -- with room at both ends,
#: and is the interval the CIE's own abridged tables use.
FIRST, LAST, STEP = 360, 830, 5

#: The observers a reference file may declare. CGATS writes OBSERVER_ANGLE and CxF
#: an observer element; both name one of these two.
OBSERVERS = {
    "2": "CIE 1931 2 Degree Standard Observer",
    "10": "CIE 1964 10 Degree Standard Observer",
}

#: The illuminants ``imaging.color.WHITE_POINTS`` knows, so that a file declaring
#: one of them can be integrated under it rather than under an assumption.
ILLUMINANTS = ("D50", "D55", "D65", "A")


def main() -> None:
    grid = np.arange(FIRST, LAST + 1, STEP, dtype=float)
    shape = colour.SpectralShape(FIRST, LAST, STEP)

    lines = [
        '"""CIE colour-matching functions and illuminant spectra, at 5 nm.',
        "",
        "Generated by ``tools/generate_cie_tables.py`` -- do not edit by hand. See that",
        "file for why these are in the repository rather than computed at runtime, and",
        "``tests/test_spectral.py`` for the check that they are right.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "#: First wavelength, last wavelength and interval, in nanometres.",
        f"SHAPE = ({FIRST}, {LAST}, {STEP})",
        "",
        "#: Colour-matching functions per observer, as (x_bar, y_bar, z_bar) triples on",
        "#: SHAPE's grid.",
        "OBSERVERS: dict[str, tuple[tuple[float, float, float], ...]] = {",
    ]
    for name, full in OBSERVERS.items():
        cmfs = colour.MSDS_CMFS[full].copy().align(shape)
        values = np.asarray(cmfs.values, dtype=float)
        lines.append(f'    "{name}": (  # {full}')
        for row in values:
            lines.append(f"        ({row[0]:.8f}, {row[1]:.8f}, {row[2]:.8f}),")
        lines.append("    ),")
    lines += ["}", "", "#: Relative spectral power per illuminant, on SHAPE's grid.",
              "ILLUMINANTS: dict[str, tuple[float, ...]] = {"]
    for name in ILLUMINANTS:
        sd = colour.SDS_ILLUMINANTS[name].copy()
        # Extrapolated where the published distribution stops short of the grid --
        # D50 is published to 780 nm and the observer runs to 830. The eye's
        # response there is under a millionth of its peak, so what is done past the
        # end cannot reach a reported value; it is held constant rather than
        # allowed to run negative, which a polynomial would.
        sd = sd.copy().extrapolate(shape).align(shape)
        values = np.asarray(sd.values, dtype=float)
        lines.append(f'    "{name}": (')
        for index in range(0, len(values), 8):
            chunk = ", ".join(f"{v:.6f}" for v in values[index:index + 8])
            lines.append(f"        {chunk},")
        lines.append("    ),")
    lines += ["}", ""]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} -- {len(grid)} wavelengths, "
          f"{len(OBSERVERS)} observers, {len(ILLUMINANTS)} illuminants")


if __name__ == "__main__":
    main()
